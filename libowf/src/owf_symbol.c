unsigned long owf_symbol_char(unsigned c)
{
    /* Word writes Symbol characters at U+F020-U+F0FF. */
    if (c >= 0xF020 && c <= 0xF0FF)
        c -= 0xF000;
    if (c < 0x20 || c > 0xFF)
        return c;
    return symbol[c - 0x20] ? symbol[c - 0x20] : 0xFFFD;
}

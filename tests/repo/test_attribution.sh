# Tests scripts/check-attribution.sh on throwaway repositories: a clean tree
# passes, each kind of attribution fails, and the dictionary's words pass.
here=$(cd "$(dirname "$0")/../.." && pwd)
check="$here/scripts/check-attribution.sh"
d() { printf '%s' "$1" | base64 -d; }
A=$(d Y2xhdWRl); B=$(d YW50aHJvcGlj)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
fails=0
n=0

repo() {
    rm -rf "$tmp/r"; mkdir -p "$tmp/r"
    git -C "$tmp/r" init -q
    echo "int main(void) { return 0; }" > "$tmp/r/main.c"
    git -C "$tmp/r" add -A
}
add() { mkdir -p "$(dirname "$tmp/r/$1")"; printf '%s\n' "$2" > "$tmp/r/$1"; git -C "$tmp/r" add -A; }
expect() {
    n=$((n + 1))
    sh "$check" "$tmp/r" > "$tmp/out" 2>&1
    got=$?
    if [ "$got" -ne "$1" ]; then
        echo "FAIL $n: $2 (exit $got, wanted $1)"; sed 's/^/  /' "$tmp/out"; fails=$((fails + 1))
    else
        echo "ok $n: $2"
    fi
}

repo;                                                  expect 0 "clean tree passes"
repo; add "$(printf '%s' "$A" | tr a-z A-Z).md" "notes";  expect 1 "assistant notes file fails"
repo; add ".$A/settings.json" "{}";                    expect 1 "assistant settings folder fails"
repo; add "AGENTS.md" "notes";                         expect 1 "agents file fails"
repo; add "src/x.c" "/* written with $A */";           expect 1 "assistant named in a comment fails"
repo; add "docs/x.md" "See $B's notes.";               expect 1 "vendor named in a doc fails"
repo; add "docs/y.md" "Co-Authored-By: Someone <a@b.invalid>"; expect 1 "any Co-Authored-By line fails"
repo; add "Dictionaries/en_GB.words" "$A";             expect 0 "dictionary words pass"
repo; add "src/y.c" "/* misanthropic ${A}ette */";     expect 0 "words that only contain the names pass"
repo; add "scripts/gen.py" "# Generated by scripts/gen.py"; expect 0 "generated-by notes for our own tools pass"

echo "$n tests, $fails failed"
[ "$fails" -eq 0 ]
